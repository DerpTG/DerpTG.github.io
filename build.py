#!/usr/bin/env python3
"""Assemble the site's five HTML pages from parts/.

Nav, <head> and footer are shared. The root .html files are generated.
Edit parts/, not them.

Run:  python build.py
"""
import io, os

SITE = os.path.dirname(os.path.abspath(__file__))
PARTS = os.path.join(SITE, 'parts')

NAV = [('index.html', 'Home'), ('projects.html', 'Projects'),
       ('lab.html', 'Lab'), ('about.html', 'About')]


def part(name):
    with io.open(os.path.join(PARTS, name), encoding='utf-8') as f:
        return f.read()


def head(page, title, desc, canon, og_desc=None, tw_desc=None,
         doc='', preload='', extra='', body_attr=''):
    """Render <!DOCTYPE> through </header>.

    Optional slots. Every page sets body_attr; the rest are index only.
      og_desc, tw_desc  shorter social-card copy. Both default to desc.
      doc               comment block between the doctype and <html>
      preload           <link rel="preload">, before the font stylesheet
      extra             extra <head> content (JSON-LD)
      body_attr         <body> attributes. .dark-top starts the nav plateless.
    """
    if og_desc is None:
        og_desc = desc
    if tw_desc is None:
        tw_desc = desc
    nav = '\n'.join(
        '      <a href="%s"%s>%s</a>' % (h, ' class="here"' if h == page else '', l)
        for h, l in NAV)
    return """<!DOCTYPE html>
<!-- Generated by build.py. Edit parts/ and re-run; edits here are overwritten. -->
{doc}<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<!-- Inline and pre-paint. Both flags have to land before the first paint.
     Setting .js from main.js flashes a solid nav over the hero for a frame
     (see NAV OVER A DARK HERO in style.css); setting the theme from there
     flashes the wrong theme. A stored choice wins over the OS preference.
     Any storage failure falls back to light rather than throwing. -->
<script>(function(){{var r=document.documentElement;r.classList.add('js');var t;
try{{t=localStorage.getItem('fn.theme')}}catch(e){{}}
if(t!=='light'&&t!=='dark'){{t=window.matchMedia&&window.matchMedia('(prefers-color-scheme: dark)').matches?'dark':'light'}}
r.setAttribute('data-theme',t)}})()</script>
<title>{title}</title>
<meta name="description" content="{desc}">
<!-- Kept in step with the theme by main.js. -->
<meta name="theme-color" content="#E7E9E4">
<link rel="canonical" href="https://felixnaroditskiy.com/{canon}">
<meta property="og:type" content="website">
<meta property="og:site_name" content="Felix Naroditskiy">
<meta property="og:title" content="{title}">
<meta property="og:description" content="{og_desc}">
<meta property="og:url" content="https://felixnaroditskiy.com/{canon}">
<meta property="og:image" content="https://felixnaroditskiy.com/img/og.png">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="{title}">
<meta name="twitter:description" content="{tw_desc}">
<meta name="twitter:image" content="https://felixnaroditskiy.com/img/og.png">
<link rel="icon" href="favicon.svg" type="image/svg+xml">
<link rel="alternate icon" href="favicon-32.png" type="image/png" sizes="32x32">
<link rel="apple-touch-icon" href="apple-touch-icon.png">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
{preload}<link href="https://fonts.googleapis.com/css2?family=Archivo:wght@400;500;600;700;800&family=IBM+Plex+Mono:wght@400;500;600&display=swap" rel="stylesheet">
<link rel="stylesheet" href="style.css">
{extra}</head>
<body{body_attr}>
<!-- Fixed background behind the whole document. Decorative. -->
<div class="sitebg" aria-hidden="true"><i class="sb-bloom"></i><i class="sb-grid"></i><i class="sb-noise"></i></div>
<header class="nav">
  <div class="wrap">
    <a class="brand" href="index.html"><i aria-hidden="true"></i>F. NARODITSKIY</a>
    <button class="navtog" id="navtog" aria-expanded="false" aria-controls="pagenav">Menu</button>
    <nav id="pagenav">
{nav}
    </nav>
    <span class="nav-act">
      <!-- Sun and moon are one mark: .ti-bite is parked off the corner for
           the sun and slides over the disc to cut the crescent. The label
           says what the click does, so it flips with the theme. -->
      <button class="themetog" id="themetog" type="button" aria-label="Switch to dark theme">
        <svg class="ti" viewBox="0 0 24 24" aria-hidden="true" focusable="false">
          <mask id="timask" maskUnits="userSpaceOnUse" x="0" y="0" width="24" height="24">
            <rect x="0" y="0" width="24" height="24" fill="#fff"/>
            <circle class="ti-bite" cx="12" cy="12" r="6.2" fill="#000"/>
          </mask>
          <circle class="ti-core" cx="12" cy="12" r="6.2" mask="url(#timask)"/>
          <g class="ti-rays" fill="none" stroke-linecap="round">
            <line x1="12" y1="1.2" x2="12" y2="3.4"/>
            <line x1="12" y1="20.6" x2="12" y2="22.8"/>
            <line x1="1.2" y1="12" x2="3.4" y2="12"/>
            <line x1="20.6" y1="12" x2="22.8" y2="12"/>
            <line x1="4.6" y1="4.6" x2="6.2" y2="6.2"/>
            <line x1="17.8" y1="17.8" x2="19.4" y2="19.4"/>
            <line x1="19.4" y1="4.6" x2="17.8" y2="6.2"/>
            <line x1="6.2" y1="17.8" x2="4.6" y2="19.4"/>
          </g>
        </svg>
      </button>
      <a class="solid" href="index.html#top">Contact me</a>
    </span>
  </div>
</header>
""".format(title=title, desc=desc, og_desc=og_desc, tw_desc=tw_desc,
           canon=canon, nav=nav, doc=doc, preload=preload, extra=extra,
           body_attr=body_attr)


