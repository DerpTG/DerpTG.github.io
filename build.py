#!/usr/bin/env python3
"""Assemble the site's five HTML pages from parts/.

Nav, <head> and footer are shared. The root .html files are generated.
Edit parts/, not them.

Run:  python build.py
"""
import io, os

SITE = os.path.dirname(os.path.abspath(__file__))
PARTS = os.path.join(SITE, 'parts')

NAV = [('index.html', 'Home'), ('projects.html', 'Projects'),
       ('lab.html', 'Lab'), ('about.html', 'About')]


def part(name):
    with io.open(os.path.join(PARTS, name), encoding='utf-8') as f:
        return f.read()


def head(page, title, desc, canon, og_desc=None, tw_desc=None,
         doc='', preload='', extra='', body_attr=''):
    """Render <!DOCTYPE> through </header>.

    Optional slots, used only by index.html:
      og_desc, tw_desc  shorter social-card copy. Both default to desc.
      doc               comment block between the doctype and <html>
      preload           <link rel="preload">, before the font stylesheet
      extra             extra <head> content (JSON-LD)
      body_attr         <body> attributes. .dark-top starts the nav plateless.
    """
    if og_desc is None:
        og_desc = desc
    if tw_desc is None:
        tw_desc = desc
    nav = '\n'.join(
        '      <a href="%s"%s>%s</a>' % (h, ' class="here"' if h == page else '', l)
        for h, l in NAV)
    return """<!DOCTYPE html>
<!-- Generated by build.py. Edit parts/ and re-run; edits here are overwritten. -->
{doc}<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<!-- Inline and pre-paint. Setting this from main.js flashes a solid nav
     over the hero for a frame. See NAV OVER A DARK HERO in style.css. -->
<script>document.documentElement.classList.add('js')</script>
<title>{title}</title>
<meta name="description" content="{desc}">
<link rel="canonical" href="https://felixnaroditskiy.com/{canon}">
<meta property="og:type" content="website">
<meta property="og:site_name" content="Felix Naroditskiy">
<meta property="og:title" content="{title}">
<meta property="og:description" content="{og_desc}">
<meta property="og:url" content="https://felixnaroditskiy.com/{canon}">
<meta property="og:image" content="https://felixnaroditskiy.com/img/og.png">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="{title}">
<meta name="twitter:description" content="{tw_desc}">
<meta name="twitter:image" content="https://felixnaroditskiy.com/img/og.png">
<link rel="icon" href="favicon.svg" type="image/svg+xml">
<link rel="alternate icon" href="favicon-32.png" type="image/png" sizes="32x32">
<link rel="apple-touch-icon" href="apple-touch-icon.png">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
{preload}<link href="https://fonts.googleapis.com/css2?family=Archivo:wght@400;500;600;700;800&family=IBM+Plex+Mono:wght@400;500;600&display=swap" rel="stylesheet">
<link rel="stylesheet" href="style.css">
{extra}</head>
<body{body_attr}>
<!-- Fixed background behind the whole document. Decorative. -->
<div class="sitebg" aria-hidden="true"><i class="sb-bloom"></i><i class="sb-grid"></i><i class="sb-noise"></i></div>
<header class="nav">
  <div class="wrap">
    <a class="brand" href="index.html"><i aria-hidden="true"></i>F. NARODITSKIY</a>
    <button class="navtog" id="navtog" aria-expanded="false" aria-controls="pagenav">Menu</button>
    <nav id="pagenav">
{nav}
    </nav>
    <span class="nav-act">
      <a class="solid" href="index.html#top">Contact me</a>
    </span>
  </div>
</header>
""".format(title=title, desc=desc, og_desc=og_desc, tw_desc=tw_desc,
           canon=canon, nav=nav, doc=doc, preload=preload, extra=extra,
           body_attr=body_attr)


